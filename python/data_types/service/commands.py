#!/usr/bin/env python3
# -*- coding=utf-8 -*-

import enum


class ServiceCommand(enum.IntEnum):
    @property
    def command(self: "ServiceCommand") -> str:
        return self.name.lower().replace("_", "-")

    BLE_ECHO_TEST = 0x00  # BLE echo test
    GET_DEBUG_LOG = 0x01
    GET_SECURE_BOOT_DIGEST = 0x02
    PING_MQTT_TELEMETRY = 0x03  # ping MQTT telemetry
    PING_HTTP = 0x04  # ping HTTP
    SET_TEST_MODE_A = 0x06
    SET_TEST_MODE_B = 0x07
    SET_DISPLAY_TEST = 0x08
    ENABLE_RELEASE_MODE = 0x0C
    GET_HARDWARE_REVISION = 0x0D
    GET_ACDC_SELF_TEST_RESULT = 0x0E
    RUN_ACDC_SELF_TEST = 0x0F

    # Device
    ASSOCIATE_DEVICE = 0x10
    REBOOT_DEVICE = 0x11
    RESET_DEVICE = 0x12
    GET_DEVICE_SERIAL_NO = 0x13
    GET_AP_VERSION = 0x15
    SET_DEVICE_POWER_STATE = 0x1A
    GET_DEVICE_POWER_STATE = 0x1B
    GET_BLE_RSSI = 0x1E
    GET_BLE_MTU = 0x1F

    # WIFI
    SCAN_WIFI = 0x30
    SET_WIFI_SSID = 0x31
    SET_WIFI_PASSWORD = 0x32
    RESET_WIFI = 0x33
    GET_WIFI_STATUS = 0x34
    GET_DEVICE_WIFI_ADDR = 0x35
    SET_WIFI_SSID_AND_PASSWORD = 0x36
    GET_WIFI_RECORDS = 0x37
    OPERATE_WIFI_RECORD = 0x38
    GET_WIFI_STATE_MACHINE = 0x39
    SET_WIFI_STATE_MACHINE = 0x3A

    # Power
    GET_CHARGE_DURATION = 0x40
    SET_CHARGING_STRATEGY = 0x43
    GET_CHARGING_STATUS = 0x44
    GET_POWER_HISTORICAL_STATS = 0x45
    SET_PORT_PRIORITY = 0x46
    GET_PORT_PRIORITY = 0x47
    GET_CHARGING_STRATEGY = 0x48
    GET_PORT_PD_STATUS = 0x49
    GET_ALL_POWER_STATISTICS = 0x4A
    TURN_ON_PORT = 0x4C
    TURN_OFF_PORT = 0x4D
    BLE_FORWARD_PORT = 0x4E
    GET_PORTS_VIN = 0x4F
    SET_STATIC_ALLOCATOR = 0x55
    GET_STATIC_ALLOCATOR = 0x56
    SET_PORT_COMPATIBILITY_SETTINGS = 0x59
    GET_PORT_COMPATIBILITY_SETTINGS = 0x5A
    SET_TEMPERATURE_MODE = 0x5B
    SET_TEMPORARY_ALLOCATOR = 0x5C
    SET_PORT_CONFIG = 0x5D
    GET_PORT_CONFIG = 0x5E
    SUBSCRIBE_PD_PCAP_STREAMING = 0x5F
    SET_PORT_TYPE = 0x60
    SET_CUSTOM_PDO_VOLTAGE = 0x61
    SET_CABLE_COMPENSATION = 0x62
    GET_CABLE_COMPENSATION = 0x63

    # Display
    SET_DISPLAY_INTENSITY = 0x70
    SET_DISPLAY_MODE = 0x71
    GET_DISPLAY_INTENSITY = 0x72
    GET_DISPLAY_MODE = 0x73
    SET_DISPLAY_FLIP = 0x74
    GET_DISPLAY_FLIP = 0x75
    SET_DISPLAY_CONFIG = 0x76
    SET_DISPLAY_STATE = 0x77
    GET_DISPLAY_STATE = 0x78
    GET_DISPLAY_ROTATION = 0x79
    SET_DISPLAY_ROTATION = 0x7A
    CLEAR_FACTORY_DM_FLAG = 0x7B
    SWITCH_FPGA_FIRMWARE = 0x7C
    SET_DISPLAY_SETUP = 0x7D
    GET_DISPLAY_SETUP = 0x7E

    # Telemetry Stream
    STREAM_PORT_STATUS = 0x80
    STREAM_DEVICE_STATUS = 0x81
    STREAM_PORT_PD_STATUS = 0x82
    STREAM_PROGRAMMER_STATUS = 0x83
    START_TELEMETRY_STREAM = 0x90
    STOP_TELEMETRY_STREAM = 0x91

    GET_DEVICE_INFO = 0x92

    SET_BLE_STATE = 0x98
    START_OTA = 0x9C

    START_PROGRAMMER = 0xA0
